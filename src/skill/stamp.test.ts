import { describe, it, expect } from "vitest";
import { stampPluginVersion } from "./stamp";
import { PLUGIN_VERSION_TOKEN, SKILL_MARKDOWN, REFERENCE_MARKDOWN, AGENTS_SECTION, SKILL_VERSION } from "./skill-content";

describe("stampPluginVersion (B-192)", () => {
    it("puts the running plugin version where the token stood, in every header", () => {
        for (const text of [SKILL_MARKDOWN, REFERENCE_MARKDOWN, AGENTS_SECTION]) {
            const stamped = stampPluginVersion(text, "7.8.9");
            expect(stamped).toContain(`schema version ${SKILL_VERSION}, generated by Dashy 7.8.9.`);
            expect(stamped).not.toContain(PLUGIN_VERSION_TOKEN);
        }
    });

    it("follows the version it is given, so a bump changes the installed text and nothing else", () => {
        const a = stampPluginVersion(SKILL_MARKDOWN, "2.2.0");
        const b = stampPluginVersion(SKILL_MARKDOWN, "2.3.0");
        expect(a).not.toBe(b);
        expect(a.replace("2.2.0", "X")).toBe(b.replace("2.3.0", "X"));
    });

    it("leaves text without the token unchanged and replaces every occurrence", () => {
        expect(stampPluginVersion("no token", "1.0.0")).toBe("no token");
        expect(stampPluginVersion(`${PLUGIN_VERSION_TOKEN} and ${PLUGIN_VERSION_TOKEN}`, "1.0.0")).toBe("1.0.0 and 1.0.0");
    });
});
